/**
 * 数字・日期・量词的读法规则（工具 3 的引擎）。
 *
 * 为什么要单独抽成一个模块，而不是写在视图里：
 *   1. 视图（app/js/views/toolbox.js）要渲染表格，校验脚本（tools/check-counters.mjs）
 *      要拿同一套规则去和内置词库对账。**一份规则、两处使用**，
 *      否则改了规则忘了改校验，校验就变成自欺欺人。
 *   2. 这个模块是**纯函数、零依赖、不碰 DOM**，所以 Node 和浏览器都能 import ——
 *      校验脚本因此不需要起浏览器，直接 import 就能跑。
 *
 * 数据可信度说明：这里的读法不是"我说了算"，凡是内置词库里存在的形式
 * （4月=しがつ、3本=さんぼん、1匹=いっぴき、20歳=はたち、1階=いっかい…），
 * 都由 tools/check-counters.mjs 逐条比对。核对不上的会直接报错。
 */

/**
 * 数字的音读基数。
 * 4=よん、7=なな、9=きゅう 是刻意选的"不会混淆"的读法：
 * し 与 4/7 混（し/しち）、く 与 9/4 混，所以单独数数用 よん/なな/きゅう。
 * 只有搭配特定量词时才变回 し/しち/く（4月=しがつ、7時=しちじ、9月=くがつ）。
 */
const DIGIT = ['ゼロ', 'いち', 'に', 'さん', 'よん', 'ご', 'ろく', 'なな', 'はち', 'きゅう'];

const BIG_UNITS = [
  { v: 1000000000000, name: 'ちょう' },
  { v: 100000000, name: 'おく' },
  { v: 10000, name: 'まん' },
];

/**
 * 百的促音便：3=さんびゃく、6=ろっぴゃく、8=はっぴゃく。
 * ⚠️ 表里已经含了数字本身（さん/ろっ/はっ），所以拼装时**不能再前缀 DIGIT**，
 *    否则会得到「さんさんびゃく」。踩过这个坑，见下面拼装代码的注释。
 */
const HYAKU = { 3: 'さんびゃく', 6: 'ろっぴゃく', 8: 'はっぴゃく' };
/** 千的促音便：3=さんぜん、8=はっせん（同样已含数字） */
const SEN = { 3: 'さんぜん', 8: 'はっせん' };

/**
 * 整数的音读。0 → ゼロ。
 * 纯算法、不查表，所以任意大小都能读（受 JS 整数精度限制，约 2^53）。
 *
 * 拼装规则：百位/千位先看有没有"已含数字的促音便整块"（HYAKU/SEN），
 * 有就用那一块（它已经含了 さん/ろっ/はっ），没有就是 [数字] + 单位名。
 * ⚠️ 两个踩过的坑，都写在这里防止再犯：
 *   1. 促音便表已含数字，若再前缀 DIGIT 会得到「さんさんびゃく」。
 *   2. 单位名**必须无条件拼上去**。曾写成 `q === 1 ? '' : (…)`，
 *      结果 100 变空串、1234 变成「にひゃくさんじゅうよん」——
 *      因为 q===1 时整块被丢掉了，连「ひゃく」都没了。
 *      正确写法是只有"数字前缀"受 q===1 影响，单位名不受影响。
 * 1000 读 せん 而不是 いっせん —— いっせん 只用在"一千〇〇"的复合词里
 * （一千円 = いっせんえん），单独说 1000 就是 せん。
 */
export function numberReading(n) {
  n = Math.floor(Math.abs(Number(n) || 0));
  if (n === 0) return 'ゼロ';
  let out = '';
  for (const u of BIG_UNITS) {
    if (n >= u.v) {
      const q = Math.floor(n / u.v);
      out += numberReading(q) + u.name;
      n -= q * u.v;
    }
  }
  if (n >= 1000) {
    const q = Math.floor(n / 1000);
    out += (SEN[q] || (q === 1 ? '' : DIGIT[q]) + 'せん');
    n -= q * 1000;
  }
  if (n >= 100) {
    const q = Math.floor(n / 100);
    out += (HYAKU[q] || (q === 1 ? '' : DIGIT[q]) + 'ひゃく');
    n -= q * 100;
  }
  if (n >= 10) {
    const q = Math.floor(n / 10);
    out += (q === 1 ? '' : DIGIT[q]) + 'じゅう';
    n -= q * 10;
  }
  if (n > 0) out += DIGIT[n];
  return out;
}

/** 日期的"日"：1〜10 与 20 是训读，必须单独记 */
export const DAYS = ['', 'ついたち', 'ふつか', 'みっか', 'よっか', 'いつか',
  'むいか', 'なのか', 'ようか', 'ここのか', 'とおか'];

/** 月份的不规则读法（4/7/9） */
export const MONTHS = { 4: 'しがつ', 7: 'しちがつ', 9: 'くがつ' };

/** 时刻的不规则读法（4/7/9） */
export const HOURS = { 4: 'よじ', 7: 'しちじ', 9: 'くじ' };

/** 分钟：1/3/4/6/8/10 有促音便或半浊音 */
export const MINUTES = { 1: 'いっぷん', 3: 'さんぷん', 4: 'よんぷん',
  6: 'ろっぷん', 8: 'はっぷん', 10: 'じゅっぷん' };

/**
 * 「〜日」的读法。
 * 规则（和词库交叉核对过 1〜10、20、30 日）：
 *   1〜10 训读；20=はつか（特殊）；14・24 的"日"读 よっか；17・27 读 しちにち；
 *   19 读 じゅうくにち（く 不是 きゅう）；29 读 にじゅうくにち。其余 = 数字 + にち。
 */
export function dayReading(d) {
  if (d >= 1 && d <= 10) return DAYS[d];
  if (d === 20) return 'はつか';
  if (d === 14 || d === 24) return numberReading(d - 4) + 'よっか';
  if (d === 17 || d === 27) return numberReading(d - 7) + 'しちにち';
  if (d === 19) return 'じゅうくにち';
  if (d === 29) return 'にじゅうくにち';
  return numberReading(d) + 'にち';
}

export function monthReading(m) {
  return MONTHS[m] || numberReading(m) + 'がつ';
}

export function hourReading(h) {
  return HOURS[h] || numberReading(h) + 'じ';
}

export function minuteReading(m) {
  return MINUTES[m] || numberReading(m) + 'ふん';
}

