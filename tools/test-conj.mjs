console.log('\n[7] 反向规则表："给定一个形态，规则是什么"');
{
  const all = ruleTable('');
  ok(all.length >= 50, `规则表不为空（${all.length} 条）`);
  // 每一类都要有
  for (const t of CHOOSABLE_TYPES) {
    ok(all.some((r) => r.type === t), `规则表里覆盖了 ${TYPE_LABELS[t]}`);
  }
  // 按关键字筛
  const te = ruleTable('て');
  ok(te.length > 0, '按「て」能筛出规则', String(te.length));
  ok(te.every((r) => r.name.includes('て') || r.rule.includes('て') || r.example.includes('て')),
    '筛出来的每一条都和「て」有关（不是把它当通配符）');
  ok(te.some((r) => r.type === 'godan' && /音便/.test(r.rule)),
    '★ 五段的て形规则里写明了"音便"（初学者最需要知道的就是这个词）');
  // ⚠️ 这一条**必须把 note 也连进来**。
  //    "一段没有音便"这句提醒是写在 note 里的，不是 rule 里。
  //    第一版只连了 rule + name + example，于是断言红了 —— 而代码里那句话明明在。
  //    这属于"断言找错了地方"，改的是断言。
  ok(te.some((r) => r.type === 'ichidan' && /没有音便|直接|不用音便/.test(
    r.rule + r.name + (r.example || '') + (r.note || ''))),
    '★ 一段的て形规则里写明"没有音便"（和五段形成对照）');

  // ★ 规则表和正向引擎必须一致 —— 否则就是"文档和代码各说一套"
  for (const [type, w] of Object.entries({ godan: '書く', ichidan: '食べる', suru: 'する', 'i-adj': '高い', 'na-adj': '静か' })) {
    const fromEngine = conjugate(w, { type }).forms;
    const fromTable = all.filter((r) => r.type === type);
    for (const f of fromEngine) {
      const row = fromTable.find((r) => r.name === f.name);
      ok(!!row, `★ 规则表里有「${TYPE_LABELS[type]}」的「${f.name}」（不能引擎有、规则表没有）`);
      if (row) {
        ok(row.rule === f.rule,
          `★ 「${f.name}」的规则文字在规则表和引擎里完全一致（不能各写一套）`,
          `表：${row.rule} ／ 引擎：${f.rule}`);
        ok(row.example === f.form, `★ 「${f.name}」的例子就是引擎的真实输出`, `表：${row.example} ／ 引擎：${f.form}`);
      }
    }
  }
}

