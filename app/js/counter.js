/** 生成「数字 + 量词」的读法。不规则的查表，其余走 数字音读 + 量词词干。 */
export function counterReading(counter, n) {
  if (counter.irregular && counter.irregular[n]) return counter.irregular[n];
  if (counter.native) return null;   // 〜つ 超出 1〜9 就没有说法了
  return numberReading(n) + (counter.base || '');
}
