function hit(x, needle) {
  const n = needle.toLowerCase();
  const tight = n.replace(/\s+/g, '');
  const hay = [(x.title || ''), (x.meaning || ''), (x.category || ''), (x.id || ''), (x.detail || ''),
    ...(x.tags || [])].join(' ').toLowerCase();
  return hay.includes(n) || hay.replace(/\s+/g, '').includes(tight);
}

const missing = [];
const found = [];
for (const [label, kw] of CAND) {
  const hits = all.filter((x) => hit(x, kw));
  if (hits.length === 0) missing.push(label);
  else found.push([label, hits.length, hits.slice(0, 3).map((h) => h.level + ':' + h.id).join(' ')]);
}

const lines = [];
