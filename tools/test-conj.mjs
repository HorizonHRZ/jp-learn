console.log('\n[6b] ★★★ 独立证据：て/た 形必须是"不需要再修词干"的形态');
{
  // ────────────────────────────────────────────────────────────────────
  // 这一层是"往返验证不够用"逼出来的，为什么值得写清楚：
  //
  // [6] 的往返验证只要求"还原回原词"。问题是：**还原器非常宽容**。
  //   实测 explainDeinflect('書きいて') 也返回「書く」——
  //   它把「いて」当后缀剥掉，剩「書き」，再靠元音行位移修回「書く」。
  //   于是 bug 版（て形产出「書きいて」）在 [6] 里**全绿**。
  //   第一轮就是被这个骗过去的：往返全绿，实际变形是错的。
  //
  // ⚠️ 我接着试了"幂等检查"（引擎输出 → 还原 → 再变 → 要能变回原样），
  //    **结果它也没用**：因为 bug 是"自洽"的 —— 同一个错规则变两次，
  //    结果当然一样，固定点检查照样通过。
  //    这是个值得记住的结论：**自洽的系统错误，抓不出来靠自洽性**。
  //
  // 真正能抓住它的是还原器里一个**独立**的字段：`stemFix`。
  //   还原器的做法是"剥后缀 + 把词干末尾的音按元音行位移修回去"。
  //   如果剥完后缀之后**不需要修**（stemFix 为空），说明给出的形态
  //   正好是它认得的规范形态；如果需要修（stemFix 非空），说明
  //   形态本身多带了一个音 —— 那正是「書きいて」的病征：
  //       書いて  → suffix=いて, stemFix=""     （规范）
  //       書きいて → suffix=いて, stemFix="きく"  （多带了一个 き）
  //
  // 所以：**五段动词的 て/た 形，stemFix 必须为空。**
  //   这不是我定的规矩，是还原器自己的形态学表说的 —— 独立证据。
  // ────────────────────────────────────────────────────────────────────
  if (!inited) {
    console.log('  （跳过：词库没就绪）');
  } else {
    const WORDS = [
      '書く', '話す', '使う', '泳ぐ', '読む', '待つ', '遊ぶ', '死ぬ', '取る',
      '歩く', '急ぐ', '呼ぶ', '探す', '持つ', '飲む', '座る', '行く',
    ];
    let checked = 0;
    let suspicious = 0;
    const bad = [];
    for (const w of WORDS) {
      const r = conjugate(w, { type: 'godan' });
      for (const name of ['て形', 'た形（简体过去）']) {
        const f = r.forms.find((x) => x.name === name);
        if (!f) continue;
        const back = explainDeinflect(f.form);
        if (!back || !back.found || !back.results.length) continue;
        const self = back.results.find((x) => x.dict === w);
        if (!self) continue;          // 还原到别的词，[6] 已经管了
        checked++;
        if (self.stemFix) {
          suspicious++;
          bad.push(`${w} 的「${name}」= ${f.form} → 还原器说它需要把词干「${self.stemFix[0]}」改成「${self.stemFix[self.stemFix.length - 1]}」才对（suffix=${self.suffix}）`);
        }
      }
    }
    ok(checked >= 25, `★ 真的检查了一批 て/た 形（${checked} 个 ≥ 25）`);
    ok(suspicious === 0,
      `★★★ 所有 て/た 形都不需要还原器再修词干（${checked - suspicious}/${checked}）`
      + ' —— 没有任何"多带一个音"的假形态',
      bad.slice(0, 6).join('；'));
  }
}

