/**
 * 数据库结构版本（IndexedDB schema version）。
 *
 * ⚠️ **加了新的 store，就必须把这里加 1。** 这是硬规矩，没有例外。
 *
 * 为什么（真实事故，2026-10）：`readingOverrides`（用户手改的汉字读音）这张表
 * 被加进了 `STORE_DEFS`，但**这里忘了加 1**，于是：
 *   · 老用户的库停在版本 2 → `existingVersion === SCHEMA_VERSION` →
 *     判定「不需要升级」→ `onupgradeneeded` 不触发 → `ensureSchema()` 不跑
 *     → **那张表永远建不出来**；
 *   · 用户改注音点保存时炸出
 *     `Failed to execute 'transaction' on 'IDBDatabase':
 *      One of the specified object stores was not found.`
 *
 * 📌 关键在于**它不是"一打开就全坏"，而是只在"改注音"这一个动作上炸** ——
 * 表面上像那个功能自己的 bug，实际根因在数据库结构版本上。
 * 而且**只要版本号不涨，再改多少保存逻辑都没用**，因为建表那条路径永远走不到。
 *
 * 现在有两道保险：
 *   ① 这段注释（给人看）；
 *   ② `db.js` 打开库之后的「结构自检」：发现缺表就明确报出来、并记进 `meta`，
 *      而不是等用户点保存时才炸（见 db.js 第 4.5 步）。
 *
 * 规则（来自 ARCHITECTURE.md 约束 2）：
 *   - 迁移只允许「增量」：新增 store / 新增 index / 逐条改写记录
 *   - 绝不允许 deleteObjectStore 或 clear() 来"重置"用户数据
 *   - 迁移前会自动生成一份快照（由 db.js 负责，不依赖调用方记得）
 *
 * ────────────────────────────────────────────────────────────────────
 * 版本 4（2026-10）：新增 `segOverrides` 表（用户手改的分词切法）。
 *
 * ⚠️ 这一次**没有重犯版本 3 的错** —— 加表的同时就把这里从 3 提到 4。
 *    为什么特别要提一句：`segOverrides` 和 `readingOverrides` 是同一种功能
 *    （用户手改的东西），如果只加表不加版本号，症状会和上次一模一样：
 *    老用户的库停在 3 → 判定"不需要升级" → `ensureSchema()` 不跑
 *    → 那张表永远建不出来 → 用户点"保存切法"时报
 *    `One of the specified object stores was not found`。
 *    同样也是**纯新增结构、没有任何数据改写**，所以下面 MIGRATIONS 里
 *    不需要（也不应该）写迁移函数：结构由 ensureSchema() 幂等补建，
 *    升级前的整包备份由 openDB 负责。
 * ────────────────────────────────────────────────────────────────────
 */
export const SCHEMA_VERSION = 4;

