lines.push('');
lines.push('=== 搜不到（真空缺，可以直接信）: ' + missing.length + ' 个 ===');
lines.push(missing.join('、'));
lines.push('');
lines.push('=== 搜到了（需人眼复核，子串匹配会高估）: ' + found.length + ' 个 ===');
for (const [l, n, ex] of found) lines.push('  ' + l.padEnd(14) + ' 命中 ' + String(n).padStart(3) + '  ' + ex);

