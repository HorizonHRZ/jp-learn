/**
 * test-conj.mjs —— 活用（变形）规则引擎 test-conj 的正确性验证
 *
 * ──────────────────────────────────────────────────────────────────────
 * 为什么这个测试特别重要
 * ──────────────────────────────────────────────────────────────────────
 * 用户是**初学者**。一个错的变形表他看不出来 —— 他会直接背下来。
 * 所以"我写的时候很仔细"完全不够，正确性只能靠机器反复验。
 *
 * 三层验证：
 *   [1] 具体形态逐条断言（把最常见、最容易被教材坑到的几个点钉死）
 *   [2] **往返验证**：本模块推出来的每个形态，丢回项目里**已有的**还原器，
 *       要求它能还原回原来的辞书形。
 *       —— 这一层最值钱：它用两个**独立实现**互相检查。
 *          如果正向规则算错了，还原器大概率还原不回去，于是红。
 *          如果两边都错成一样，那说明错在"日语本身的理解"上，
 *          这种错静态断言也抓不到 —— 至少要如实说明这一层的边界。
 *   [3] 反向规则表（"给定一个形态，规则是什么"）不为空、且和正向结果一致
 *
 * 用法：node tools/test-conj.mjs
 */
import { initTokenizer, explainDeinflect } from './tokenizer.js';
import { conjugate, detectType, ruleTable, TYPE_LABELS, CHOOSABLE_TYPES } from '../app/js/conj.js';

let pass = 0;
let fail = 0;
const failures = [];
function ok(cond, name, extra = '') {
  if (cond) { pass++; }
  else { fail++; failures.push(name + (extra ? '  — ' + extra : '')); console.log(`  ✗ ${name}${extra ? '  — ' + extra : ''}`); }
}
const eq = (a, b, name) => ok(a === b, name, `期望 ${JSON.stringify(b)}，实际 ${JSON.stringify(a)}`);

const form = (res, name) => {
  const f = res.forms.find((x) => x.name === name);
  return f ? f.form : '(没有这一条)';
};

