/**
 * 写内容之前先审计：候选语法点里，哪些**库里还没有**。
 *
 * ⚠️ 为什么每次都要跑这个（这是踩出来的规矩，不是谨慎）：
 *   语法库有 366 条了，"我记不记得写过"已经完全不可靠。
 *   已经发生过三次：准备写的条目其实早就有，写进去就是重复内容。
 *   而且**子串匹配会高估覆盖率**（「ものだ」会被 N2 的「〜というものだ」骗到），
 *   所以判成"有"的必须人眼复核，判成"缺"的可以直接信。
 *
 * ── 两种搜法的分工（**两个都要跑，只跑一个会得出错结论**）──────────
 *   脚本                     搜的范围                 错了会往哪边错
 *   ─────────────────────── ──────────────────────── ─────────────────
 *   audit-gap.mjs（本文件）   只看字段                 会**假有**（子串匹配高估）
 *                            （title/meaning/          → 判"有"的必须人眼复核
 *                              category/id/detail/tags）
 *   search-json.mjs          整条 JSON                会**假缺**（某条只是被
 *                            （连例句、注意事项）       别人的例句提到过）
 *                                                        → 判"缺"的也要看一眼
 *
 *   规矩：**两个都判"缺"的，才是真缺口。**
 *   两个的候选词表是**各写各的**（不是同一份），所以也别指望两边逐词对得上 ——
 *   要比的是"同一个词，两个判据各说什么"。
 *
 *   ⚠️ 这个分工写在 `使用说明.md` 的自检清单里，也由
 *      `test-grammar.mjs [3]` 断言（两个脚本必须看到同一个条数）——
 *      因为**两个脚本各自重新解析了一遍 data/grammar/*.json**，
 *      将来数据目录/字段一变，它们会各说各话而且不报错。
 *
 * 用法：node tools/audit-gap.mjs
 */
import fs from 'node:fs';
